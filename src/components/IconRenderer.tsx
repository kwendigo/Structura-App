interface IconRendererProps extends LucideProps {
  name: string;
}

export const IconRenderer: React.FC<IconRendererProps> = ({
  name,
  strokeWidth = 2.5,
  ...props
}) => {
  const cleanName = normalizeIconName(name || '');
  const iconId = legacyIconAliases[cleanName] || cleanName;
  const icon = iconMap.get(normalizeIconName(iconId)) || AVAILABLE_ICONS[0].icon;
  if (isFontAwesomeIcon(icon)) {
    const [iconWidth, iconHeight] = icon.icon;
    const width = getRequestedIconSize(props.className, 'w') * 0.8;
    const height = getRequestedIconSize(props.className, 'h') * 0.8;
    const aspectRatio = iconWidth / iconHeight;
    const fitWidth = Math.min(width, height * aspectRatio);
    const fitHeight = Math.min(height, width / aspectRatio);
    const className = props.className
      ?.split(/\s+/)
      .filter((name) => !/^(?:[a-z]+:)*(?:w-|h-|min-w-|min-h-|max-w-|max-h-|text-(?:xs|sm|base|lg|xl|[0-9]+xl|\[.*\]))/.test(name))
      .concat('shrink-0')
      .join(' ');
    return (
      <FontAwesomeIcon
        icon={icon}
        className={className}
        style={{
          ...props.style,
          width: `${fitWidth}px`,
          height: `${fitHeight}px`,
          minWidth: `${fitWidth}px`,
          minHeight: `${fitHeight}px`,
        }}
        role={props.role}
        aria-label={props['aria-label']}
      />
    );
  }
  const Component = icon;
  const className = `${props.className || ''} scale-[0.8]`.trim();
  return <Component {...props} className={className} strokeWidth={strokeWidth} />;
};

export const isFontAwesomeIcon = (icon: IconComponent): icon is IconDefinition =>
  typeof icon === 'object' && 'icon' in icon && Array.isArray(icon.icon);
