export interface IconItem {
  id: string;
  label: string;
  category: string;
  icon: React.FC<LucideProps>;
}

const createAdditionalIcons = (
  category: string,
  icons: React.FC<LucideProps>[]
): IconItem[] =>
  icons.map((icon) => {
    const label = icon.displayName;
    if (!label) {
      throw new Error('Lucide icon is missing a display name.');
    }

    return {
      id: label.toLowerCase(),
      label: label.replace(/([a-z0-9])([A-Z])/g, '$1 $2'),
      category,
      icon,
    };
  });

