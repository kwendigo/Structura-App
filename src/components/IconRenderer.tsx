const iconMap = new Map(AVAILABLE_ICONS.map(({ id, icon }) => [normalizeIconName(id), icon]));
const getRequestedIconSize = (className: string | undefined, dimension: 'w' | 'h') => {
  const matchingClass = className?.split(/\s+/).find((name) => {
    const match = name.match(/^(?:[a-z]+:)*(?:w|h)-(\d+(?:\.\d+)?)$/);
    return match?.[0].endsWith(`${dimension}-${match[1]}`);
  });
  const match = matchingClass?.match(/(?:^|:)(?:w|h)-(\d+(?:\.\d+)?)$/);
  return match ? Number(match[1]) * 4 : 36;
};

